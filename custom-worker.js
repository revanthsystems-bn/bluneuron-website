/**
 * The Worker entry point for the Cloudflare build — THIS BRANCH ONLY.
 *
 * `wrangler.jsonc` points `main` here instead of at `.open-next/worker.js`,
 * and every request this file does not handle itself is delegated, unchanged,
 * to that generated handler. Nothing else in the repo imports this file: the
 * Vercel build (`next build` / `next start`) and the GoDaddy build never read
 * `wrangler.jsonc`, so neither host can take this path. This is the "custom
 * worker" entry point the adapter documents:
 * https://opennext.js.org/cloudflare/howtos/custom-worker
 *
 * ---------------------------------------------------------------------------
 * WHY IT EXISTS: RANGE REQUESTS FOR THE HERO VIDEO
 * ---------------------------------------------------------------------------
 * Workers Static Assets answers a `Range:` request with `200` and the whole
 * file, and sends no `Accept-Ranges` header. Verified on the live site before
 * this file existed:
 *
 *     $ curl -sD- -o/dev/null -H "Range: bytes=0-1" \
 *         https://www.bluneuron.com/media/iriz/video/iriz-loop.mp4
 *     HTTP/1.1 200 OK
 *     Content-Length: 739869      # the whole file, for a 2-byte request
 *     (no Accept-Ranges)
 *
 * Chrome and Firefox tolerate that and play the video. iOS Safari does NOT:
 * it requires `206 Partial Content` for `<video>`, and without it the hero
 * degrades to its poster frame on every iPhone. So the two video files are
 * routed through this Worker — see `assets.run_worker_first` in
 * `wrangler.jsonc` — and answered here, with a real 206.
 *
 * The rest of `public/` is untouched and still served straight off the edge,
 * never invoking the Worker: ~12 MB of product photography that stays free
 * and unmetered. Only `/media/**.mp4` and `/media/**.webm` are intercepted,
 * which today is two files.
 *
 * The bytes are read from the ASSETS binding, so the video is still a static
 * asset: uploaded beside the Worker, not counted toward the Worker size
 * limit, and NOT inlined into the bundle. Do not "simplify" this by importing
 * the file as data — that would move a megabyte of video into the Worker
 * script and bill every request for it.
 */

// @ts-ignore .open-next/worker.js is generated by `opennextjs-cloudflare build`
import { default as openNextHandler } from './.open-next/worker.js';

// The generated worker also exports DOQueueHandler, DOShardedTagCache and
// BucketCachePurge. They are deliberately NOT re-exported here: all three
// serve the R2/queue incremental cache, and open-next.config.ts uses
// `staticAssetsIncrementalCache`, so `wrangler.jsonc` declares no Durable
// Object bindings for them. If this site ever moves to `r2IncrementalCache`,
// add the bindings AND re-export the classes from here, or the deploy will
// fail on a binding whose class the entry point does not export.

/**
 * Paths this Worker answers itself. Anything else that reaches it — every
 * page, /_next/image, and any non-video file under /media/ that a future
 * `run_worker_first` rule happens to catch — falls through to OpenNext.
 */
const RANGEABLE_MEDIA = /^\/media\/.+\.(mp4|webm)$/;

/**
 * Content types, stated here rather than taken from the asset response. The
 * asset worker gets these right today; stating them keeps the 206 and the
 * 200 identical no matter what it decides to send.
 */
const CONTENT_TYPES = { mp4: 'video/mp4', webm: 'video/webm' };

/**
 * 30 days, and deliberately NOT `immutable` with a one-year age. These
 * filenames are stable and not content-hashed (`iriz-loop.mp4`), so a year
 * of immutable caching would pin a replaced video in visitors' browsers for
 * a year with no way to bust it. Thirty days is long enough that repeat
 * visits never re-download it, and it recovers on its own. The asset ETag is
 * passed through below, so a revalidation after that window is a 304 and not
 * a re-transfer. If a video is ever replaced, change the filename.
 */
const CACHE_CONTROL = 'public, max-age=2592000';

/**
 * Parse a single-range `Range:` header against a known body size.
 *
 * Returns `{ start, end }` (inclusive, clamped to the body); the string
 * 'unsatisfiable' for a syntactically valid range that falls outside the
 * body, which RFC 9110 says must be answered 416 and is how a client
 * discovers its idea of the file is stale; or `null` for anything this
 * Worker declines to interpret — a non-bytes unit, a multi-range header
 * (`bytes=0-99,200-299`, legal but not something a video element sends), or
 * garbage. A `null` is served as a normal 200, exactly as if the header had
 * not been there.
 */
function parseSingleRange(header, size) {
  const match = /^bytes=(\d*)-(\d*)$/.exec(header.trim());
  if (!match) return null;

  const [, rawStart, rawEnd] = match;
  if (rawStart === '' && rawEnd === '') return null;

  let start;
  let end;

  if (rawStart === '') {
    // `bytes=-N`: the last N bytes. N=0 is unsatisfiable per the spec.
    const suffixLength = Number(rawEnd);
    if (suffixLength === 0) return 'unsatisfiable';
    start = Math.max(0, size - suffixLength);
    end = size - 1;
  } else {
    start = Number(rawStart);
    if (start >= size) return 'unsatisfiable';
    end = rawEnd === '' ? size - 1 : Math.min(Number(rawEnd), size - 1);
    if (end < start) return 'unsatisfiable';
  }

  return { start, end };
}

/** Headers shared by every response this Worker writes for a media file. */
function mediaHeaders(extension, assetResponse) {
  const headers = new Headers({
    'Content-Type': CONTENT_TYPES[extension],
    'Cache-Control': CACHE_CONTROL,
    // The point of the exercise: iOS Safari looks for this before it will
    // ask for a range at all.
    'Accept-Ranges': 'bytes',
  });

  // Pass the asset's validators through, so browser cache revalidation keeps
  // working as it did when the asset worker served these files directly.
  for (const header of ['ETag', 'Last-Modified']) {
    const value = assetResponse.headers.get(header);
    if (value) headers.set(header, value);
  }

  return headers;
}

/**
 * Serve one media file, with range support, out of the ASSETS binding.
 *
 * The asset worker ignores `Range:`, so there is nothing to forward: this
 * fetches the whole object and slices it. The buffer is bounded by
 * Cloudflare's own 25 MiB per-asset limit, and the two files here are 723 KB
 * and 651 KB, so it is never large. If a genuinely large video is ever added,
 * this is the line to revisit.
 *
 * The fetch is built as a clean GET rather than a pass-through of the
 * client's request, on purpose: forwarding `If-None-Match` to the asset
 * worker could come back `304` with no body, leaving nothing to slice.
 */
async function serveMedia(request, env, extension) {
  const assetResponse = await env.ASSETS.fetch(new Request(request.url, { method: 'GET' }));

  // A missing or failed asset is the asset worker's answer to give, not ours.
  if (!assetResponse.ok) return assetResponse;

  const rangeHeader = request.headers.get('Range');
  const body = await assetResponse.arrayBuffer();
  const size = body.byteLength;
  const headers = mediaHeaders(extension, assetResponse);
  const isHead = request.method === 'HEAD';

  const whole = () => {
    headers.set('Content-Length', String(size));
    return new Response(isHead ? null : body, { status: 200, headers });
  };

  if (!rangeHeader) return whole();

  // `If-Range` is the client saying "only honour this range if the file is
  // still the one I have". If it does not match, the spec requires the whole
  // file rather than a slice of a different one.
  const ifRange = request.headers.get('If-Range');
  const etag = headers.get('ETag');
  if (ifRange && etag && ifRange.trim() !== etag) return whole();

  const range = parseSingleRange(rangeHeader, size);

  if (range === 'unsatisfiable') {
    headers.set('Content-Range', `bytes */${size}`);
    return new Response(null, { status: 416, headers });
  }

  if (range === null) return whole();

  const { start, end } = range;
  headers.set('Content-Range', `bytes ${start}-${end}/${size}`);
  headers.set('Content-Length', String(end - start + 1));

  return new Response(isHead ? null : body.slice(start, end + 1), { status: 206, headers });
}

export default {
  async fetch(request, env, ctx) {
    const { pathname } = new URL(request.url);

    if (RANGEABLE_MEDIA.test(pathname) && (request.method === 'GET' || request.method === 'HEAD')) {
      const extension = pathname.slice(pathname.lastIndexOf('.') + 1);
      return serveMedia(request, env, extension);
    }

    // Everything else is the Next.js app, unchanged.
    return openNextHandler.fetch(request, env, ctx);
  },
};
