import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('  [pageerror]', String(e).slice(0, 200)));
await p.goto('http://127.0.0.1:4311/', { waitUntil: 'networkidle' });
await p.locator('button[aria-haspopup="dialog"]').first().click();
const dialog = p.locator('[role="dialog"]');
await dialog.waitFor({ state: 'visible' });
const pending = dialog.locator('button').filter({ hasText: /Buy on (Amazon|Flipkart)/ });
console.log('pending count:', await pending.count());
await pending.first().click();
await p.waitForTimeout(400);
console.log('active after pending click:', await p.evaluate(() => document.activeElement?.tagName));
await p.keyboard.press('Escape');
await p.waitForTimeout(800);
console.log('dialog count after Escape:', await dialog.count());
if (await dialog.count()) console.log('still visible:', await dialog.isVisible());
await b.close();
